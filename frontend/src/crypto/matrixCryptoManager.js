/**
 * PulseChat Matrix-SDK Crypto Client Identity & Prekey Manager (Milestone 1)
 *
 * Uses @matrix-org/matrix-sdk-crypto-wasm (Rust vodozemac core)
 * Implements the asynchronous push/pull state machine for OlmMachine:
 * 1. Initializes WASM module and local IndexedDB-backed OlmMachine.
 * 2. Generates KeysUploadRequest containing Curve25519 identity key, Ed25519 signing key,
 *    and a pool of signed one-time prekeys (OTKs).
 * 3. Handles request fulfillment by submitting public prekeys to /api/keys/upload
 *    and passing back the server acknowledgment via markRequestAsSent().
 *
 * IMPORTANT: User messaging in ChatWindow.jsx remains untouched in Milestone 1.
 */

let wasmInitPromise = null;
let activeOlmMachine = null;
let isInitialized = false;

/**
 * Initializes the WebAssembly binary if not already loaded.
 */
export async function ensureWasmInitialized() {
  if (!wasmInitPromise) {
    wasmInitPromise = (async () => {
      const { initAsync } = await import('@matrix-org/matrix-sdk-crypto-wasm');
      await initAsync();
    })();
  }
  return wasmInitPromise;
}

/**
 * Formats a PulseChat userId into a valid Matrix UserId (@id:domain).
 */
export function formatMatrixUserId(userId) {
  const clean = String(userId || '').replace(/^@/, '').replace(/:.*$/, '').trim();
  return `@${clean}:pulsechat.local`;
}

async function _performInitMatrixCrypto({ userId, deviceId, storePassphrase = '' }) {
  if (typeof window !== 'undefined' && !window.indexedDB) {
    throw new Error('DURABLE_STORAGE_UNAVAILABLE: IndexedDB is required for Matrix OlmMachine persistence.');
  }

  await ensureWasmInitialized();

  const { OlmMachine, UserId, DeviceId } = await import('@matrix-org/matrix-sdk-crypto-wasm');

  if (activeOlmMachine) {
    try {
      activeOlmMachine.close();
    } catch (_) {}
    activeOlmMachine = null;
    isInitialized = false;
  }

  const matrixUserId = new UserId(formatMatrixUserId(userId));
  const matrixDeviceId = new DeviceId(String(deviceId).trim());
  const storeName = `pulsechat_crypto_${String(userId).trim()}`;

  // Initialize OlmMachine with mandatory IndexedDB persistence
  activeOlmMachine = await OlmMachine.initialize(
    matrixUserId,
    matrixDeviceId,
    storeName,
    storePassphrase || undefined
  );

  isInitialized = true;
  return activeOlmMachine;
}

/**
 * Initialize or open the OlmMachine for the current user and device.
 * Enforces mandatory durable IndexedDB storage and safe cross-tab coordination.
 *
 * @param {Object} options
 * @param {string} options.userId - PulseChat user ID
 * @param {string} options.deviceId - Unique device ID (e.g. from localStorage/UUID)
 * @param {string} [options.storePassphrase] - Optional passphrase for IndexedDB encryption
 * @returns {Promise<Object>} The initialized OlmMachine instance
 */
export async function initMatrixCrypto({ userId, deviceId, storePassphrase = '' }) {
  if (!userId || !deviceId) {
    throw new Error('userId and deviceId are required to initialize Matrix crypto');
  }

  const lockName = `pulsechat_matrix_init_${String(userId).trim()}`;
  if (typeof navigator !== 'undefined' && navigator.locks && typeof navigator.locks.request === 'function') {
    return await navigator.locks.request(lockName, async () => {
      return await _performInitMatrixCrypto({ userId, deviceId, storePassphrase });
    });
  }

  return await _performInitMatrixCrypto({ userId, deviceId, storePassphrase });
}

/**
 * Returns the currently active OlmMachine instance.
 */
export function getActiveOlmMachine() {
  return activeOlmMachine;
}

/**
 * Checks whether Matrix crypto has been initialized.
 */
export function isCryptoReady() {
  return isInitialized && activeOlmMachine !== null;
}

/**
 * Processes all pending outgoing requests generated by the OlmMachine
 * (e.g. KeysUploadRequest, KeysQueryRequest, KeysClaimRequest).
 *
 * @param {Function} fetchWithAuth - Authorized fetch or Axios function
 * @param {string} apiBaseUrl - Base API URL (e.g. '/api/keys')
 * @returns {Promise<{ uploaded: number, queries: number, claims: number }>}
 */
export async function syncOutgoingRequests(fetchWithAuth, apiBaseUrl = '/api/keys') {
  if (!activeOlmMachine) {
    throw new Error('OlmMachine is not initialized');
  }

  const { RequestType } = await import('@matrix-org/matrix-sdk-crypto-wasm');
  const requests = await activeOlmMachine.outgoingRequests();
  const summary = { uploaded: 0, queries: 0, claims: 0 };

  for (const request of requests) {
    try {
      if (request.type === RequestType.KeysUpload) {
        // Upload device keys and one-time prekeys
        const res = await fetchWithAuth(`${apiBaseUrl}/upload`, {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: request.body
        });

        // Fail-closed on HTTP errors: do NOT mark as sent so the request remains retryable
        if (!res || !res.ok) {
          throw new Error(`KeysUpload HTTP failed with status ${res?.status || 'network_error'}`);
        }

        const data = await res.json();
        // Validate application-level success payload matching Matrix UploadKeysResponse contract
        if (!data || typeof data !== 'object' || !data.one_time_key_counts) {
          throw new Error('KeysUpload response missing required one_time_key_counts contract');
        }

        const matrixResponse = { one_time_key_counts: data.one_time_key_counts };
        await activeOlmMachine.markRequestAsSent(request.id, request.type, JSON.stringify(matrixResponse));
        summary.uploaded++;
      } else if (request.type === RequestType.KeysQuery) {
        // Query device identities
        const res = await fetchWithAuth(`${apiBaseUrl}/query`, {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: request.body
        });

        if (!res || !res.ok) {
          throw new Error(`KeysQuery HTTP failed with status ${res?.status || 'network_error'}`);
        }

        const data = await res.json();
        // Validate application-level success payload matching Matrix QueryKeysResponse contract
        if (!data || typeof data !== 'object' || !data.device_keys) {
          throw new Error('KeysQuery response missing required device_keys contract');
        }

        const matrixResponse = { device_keys: data.device_keys, failures: data.failures || {} };
        await activeOlmMachine.markRequestAsSent(request.id, request.type, JSON.stringify(matrixResponse));
        summary.queries++;
      } else if (request.type === RequestType.KeysClaim) {
        // Claim one-time prekeys
        const res = await fetchWithAuth(`${apiBaseUrl}/claim`, {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: request.body
        });

        if (!res || !res.ok) {
          throw new Error(`KeysClaim HTTP failed with status ${res?.status || 'network_error'}`);
        }

        const data = await res.json();
        // Validate application-level success payload matching Matrix ClaimKeysResponse contract
        if (!data || typeof data !== 'object' || !data.one_time_keys) {
          throw new Error('KeysClaim response missing required one_time_keys contract');
        }

        const matrixResponse = { one_time_keys: data.one_time_keys, failures: data.failures || {} };
        await activeOlmMachine.markRequestAsSent(request.id, request.type, JSON.stringify(matrixResponse));
        summary.claims++;
      } else if (request.type === RequestType.ToDevice) {
        // Send ephemeral to-device event for Olm/Megolm session establishment
        const res = await fetchWithAuth(`${apiBaseUrl}/to_device`, {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({
            eventType: request.event_type,
            txnId: request.txn_id,
            messages: typeof request.body === 'string' ? JSON.parse(request.body) : request.body
          })
        });

        if (!res || !res.ok) {
          throw new Error(`ToDevice HTTP failed with status ${res?.status || 'network_error'}`);
        }

        const data = await res.json();
        if (!data || typeof data !== 'object') {
          throw new Error('ToDevice response invalid');
        }

        // Matrix sendToDevice endpoint response is an empty object {}
        await activeOlmMachine.markRequestAsSent(request.id, request.type, '{}');
        summary.toDevice = (summary.toDevice || 0) + 1;
      }
    } catch (err) {
      // Diagnostic log without secrets. Request remains in OlmMachine's queue for next sync retry.
      console.warn(`[MatrixCrypto] Outgoing request ${request.id} (type ${request.type}) failed and kept retryable:`, err.message);
    }
  }

  return summary;
}

/**
 * Query device list and public identity keys for a user according to SDK protocol.
 */
export async function queryUserDevices(userId) {
  if (!activeOlmMachine) throw new Error('OlmMachine is not initialized');
  const { UserId } = await import('@matrix-org/matrix-sdk-crypto-wasm');
  const matrixUserId = new UserId(formatMatrixUserId(userId));
  return await activeOlmMachine.getUserDevices(matrixUserId);
}

/**
 * Request missing Olm Double Ratchet sessions for target users according to SDK protocol.
 * Generates KeysClaimRequest in OlmMachine's outgoing queue.
 */
export async function requestMissingSessionsForUsers(userIds = []) {
  if (!activeOlmMachine) throw new Error('OlmMachine is not initialized');
  const { UserId } = await import('@matrix-org/matrix-sdk-crypto-wasm');
  const matrixUserIds = userIds.map(id => new UserId(formatMatrixUserId(id)));
  return await activeOlmMachine.getMissingSessions(matrixUserIds);
}

/**
 * Closes the OlmMachine and releases associated IndexedDB handles and memory.
 */
export function closeMatrixCrypto() {
  if (activeOlmMachine) {
    try {
      activeOlmMachine.close();
    } catch (_) {}
    activeOlmMachine = null;
  }
  isInitialized = false;
}
