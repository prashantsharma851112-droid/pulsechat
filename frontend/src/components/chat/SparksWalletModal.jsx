export const formatTxDate = (dateStr) => {
  if (!dateStr) return '';
  try {
    const d = new Date(dateStr);
    return d.toLocaleDateString('en-IN', {
      day: 'numeric',
      month: 'short',
      year: 'numeric',
      hour: '2-digit',
      minute: '2-digit',
      hour12: true
    });
  } catch (e) {
    return '';
  }
};

export const generateProofReceiptText = (transactions = [], user) => {
  const nowStr = new Date().toLocaleString('en-IN', {
    day: 'numeric',
    month: 'short',
    year: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
    hour12: true
  });
  let totalSpent = 0;
  let totalEarned = 0;
  transactions.forEach(t => {
    if (t.type === 'credit') totalEarned += Number(t.amount) || 0;
    else if (t.type === 'debit') totalSpent += Number(t.amount) || 0;
  });
  const netAmount = totalEarned - totalSpent;

  let text = `⚡ PULSECHAT SPARKS OFFICIAL LEDGER PROOF ⚡\n`;
  text += `==================================================\n`;
  text += `Account: @${user?.username || 'User'} (${user?.displayName || 'PulseChat User'})\n`;
  text += `Export Timestamp: ${nowStr}\n`;
  text += `Ledger Engine: PulseChat Proof Engine (MongoDB Verified)\n`;
  text += `Total Records: ${transactions.length}\n`;
  text += `Summary: ${totalEarned > 0 ? `+${totalEarned} Earned` : ''} ${totalSpent > 0 ? `-${totalSpent} Spent` : ''} (Net: ${netAmount >= 0 ? `+${netAmount}` : netAmount} ⚡)\n`;
  text += `==================================================\n\n`;
  text += `TRANSACTION BREAKDOWN:\n`;
  text += `--------------------------------------------------\n`;

  transactions.forEach((tx, idx) => {
    const isCredit = tx.type === 'credit';
    const dateFormatted = formatTxDate(tx.createdAt);
    text += `[#${idx + 1}] ${tx.title || (isCredit ? 'Received Sparks' : 'Sent Sparks')}\n`;
    text += `    • Type: ${isCredit ? 'CREDIT (+)' : 'DEBIT (-)'}\n`;
    text += `    • Amount: ${isCredit ? `+${tx.amount}` : `-${tx.amount}`} Sparks ⚡\n`;
    text += `    • Date & Time: ${dateFormatted}\n`;
    if (tx.description) {
      text += `    • Details: ${tx.description}\n`;
    }
    if (tx.relatedUserName) {
      text += `    • Related User: @${tx.relatedUserName}\n`;
    }
    text += `    • Ledger Ref ID: ${tx._id || tx.id || 'N/A'}\n\n`;
  });

  text += `--------------------------------------------------\n`;
  const signature = `PULSE-PROOF-${Date.now().toString(36).toUpperCase()}-${(user?._id || user?.id || 'AUTH').slice(-6).toUpperCase()}`;
  text += `🔒 Verified Proof Signature: ${signature}\n`;
  text += `Official Digital Receipt generated by PulseChat Ledger Engine.\n`;
  return text;
};

